package contract

// Storage — интерфейс, реализуемый поставщиками постоянного хранилища.
// Контракт границ: Set сохраняет копию переданного value; Get возвращает
// защитную копию — вызывающий может мутировать полученный срез, не затрагивая
// хранилище.
type Storage interface {
	Set(key string, value []byte)

	Get(key string) ([]byte, bool)

	// HasData возвращает true, если хранилище содержит постоянные данные:
	// хотя бы один сохранённый скалярный ключ либо заведённый журнал, включая
	// пустой. Пустое хранилище без журнала даёт false.
	HasData() bool
}

// LogWriteResult — наблюдаемый результат операции записи журнала.
//
// BytesWritten — байты завершённой записи журнала вместе с её кадрированием:
// заголовок файла, заголовки пакетов, служебные поля записей и Data. Writes —
// число логических записей операции: в штатном состоянии 1 для операции,
// изменившей носитель, иначе 0. Нормализация незавершённого хвоста после
// перезапуска добавляет свои байты и записи к результату следующей операции:
// возможны Writes=2 либо Writes=1 у логического no-op. Это не число системных
// вызовов записи и не физические байты носителя.
//
// Операция, не изменившая кодированное представление журнала (равные индексы,
// термы, типы и байты Data), не выполняет ввода-вывода и возвращает нулевой
// результат. Семантически равные значения вроде map могут кодироваться иначе,
// поэтому логическое равенство произвольного значения не обещается.
type LogWriteResult struct {
	BytesWritten uint64
	Writes       uint64
}

// LogStorage — Storage с операциями журнала Raft. Индексы журнала
// абсолютные: они не сбрасываются при уплотнении и сохраняют смысл между
// перезапусками. Гарантия долговечности: после возврата изменившей носитель
// операции журнал переживает завершение процесса и отказ питания в модели
// носителя (синхронизация файла, а при атомарной замене — и каталога).
// Ошибки валидации, кодирования и ввода-вывода публичных записей следуют
// стратегии немедленного отказа: успешный возврат при незакреплённых данных
// запрещён. Внутренние помощники реализаций возвращают ошибки, чтобы путь
// отказа был проверяем тестами без завершения процесса.
//
// Владелец журнала — вызывающий. StoreLogEntries и RewriteLog читают
// entries и их Data синхронно и не удерживают ссылок на изменяемые значения
// после возврата; реализация хранит собственное кодированное представление.
// LoadLog возвращает новый независимый граф значений, а не ссылку на
// внутреннее состояние. Поверхностное клонирование срезов этот контракт не
// выполняет. Пользовательские GobEncoder/GobDecoder обязаны давать
// независимое значение без внешних изменяемых ссылок.
//
// В режиме инкрементальной персистентности ключ "log" зарезервирован:
// Set("log", …) завершается немедленно, Get("log") возвращает nil,false,
// журнал читают LoadLog. Прочие ключи и скалярный формат остаются на прежнем
// пути. HasData для хранилища журнала истинен и при наличии созданного
// журнала, даже пустого.
type LogStorage interface {
	Storage

	// StoreLogEntries атомарно заменяет сохранённый суффикс журнала, начиная
	// с абсолютного индекса fromIndex, записями entries. entries начинаются
	// ровно с fromIndex, индексы идут подряд, без переполнения; пустые
	// entries удаляют суффикс, а вызов на позиции lastIndex+1 является
	// логическим no-op. Для непустого журнала допустим диапазон
	// [firstIndex, lastIndex+1], включая 0. Индекс выше lastIndex+1 или ниже
	// firstIndex — нарушение контракта, а не молчаливый no-op. Для
	// существующего пустого журнала допустим любой fromIndex≥0; непустые
	// entries начинаются с него. На отсутствующем журнале вызов запрещён:
	// первый персист выполняет RewriteLog.
	StoreLogEntries(fromIndex int, entries []LogEntry) LogWriteResult

	// RewriteLog заменяет весь сохранённый журнал записями entries, включая
	// создание пустого журнала. Непустой набор имеет любой firstIndex≥0 и
	// последующие непрерывные индексы. Операция применяется при первом
	// персисте свежего узла, уплотнении и установке снимка. Оба метода
	// записи синхронны; их ошибка завершает процесс без успешного возврата.
	RewriteLog(entries []LogEntry) LogWriteResult

	// LoadLog возвращает сохранённый журнал. Незавершённый хвост отбрасывается
	// (потребитель получает только целые пакеты), ошибки формата и повреждения
	// возвращаются как ошибка до возврата неполного результата. Отсутствующий
	// журнал даёт ErrLogNotFound, существующий пустой — пустой срез и nil.
	// Ошибка чтения или декодирования не маскируется отсутствием журнала.
	LoadLog() ([]LogEntry, error)
}
